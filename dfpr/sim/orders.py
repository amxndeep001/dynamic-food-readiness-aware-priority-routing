"""Orders: the generated demand stream and the runtime order state.

Two classes keep the information boundary explicit:

* ``OrderSpec`` is what the world generator produces, *including* the true
  prep time. Only the simulator ever sees it.
* ``Order`` is the runtime record that dispatchers can read. It contains the
  *estimated* prep time only; ``ready_at`` is filled in when the FOOD_READY
  event actually happens. So no dispatcher can peek at the true ready time.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

import numpy as np

from sim.city import City

HOUR = 3600.0


class OrderStatus(Enum):
    PLACED = "PLACED"  # waiting for a rider (eligible for dispatch)
    ASSIGNED = "ASSIGNED"  # rider on the way to / waiting at the restaurant
    PICKED_UP = "PICKED_UP"  # rider on the way to the customer
    DELIVERED = "DELIVERED"
    UNSERVED = "UNSERVED"  # still open when the simulation ended


@dataclass(frozen=True)
class OrderSpec:
    """One generated order, including the hidden true prep time."""

    id: int
    restaurant_node: int
    customer_node: int
    placed_at: float
    est_prep_s: float
    actual_prep_s: float
    deadline: float


@dataclass
class Order:
    """Runtime state of an order, visible to dispatchers (no true prep time)."""

    id: int
    restaurant_node: int
    customer_node: int
    placed_at: float
    est_prep_s: float
    deadline: float
    status: OrderStatus = OrderStatus.PLACED
    assigned_at: float | None = None
    rider_id: int | None = None
    rider_arrived_at: float | None = None
    ready_at: float | None = None  # set by FOOD_READY, i.e. only once it is observable
    picked_at: float | None = None
    delivered_at: float | None = None
    distance_m: float = 0.0  # rider distance for this order (to restaurant + to customer)

    @property
    def est_ready_at(self) -> float:
        return self.placed_at + self.est_prep_s

    @classmethod
    def from_spec(cls, spec: OrderSpec) -> Order:
        return cls(spec.id, spec.restaurant_node, spec.customer_node, spec.placed_at, spec.est_prep_s, spec.deadline)


def arrival_rate(t: float, base_per_hour: float, peaks: list[list[float]]) -> float:
    """Orders per second at time t (seconds since midnight).

    ``peaks`` is a list of ``[start_hour, end_hour, multiplier]`` windows.
    """
    hour = t / HOUR
    mult = 1.0
    for start_h, end_h, m in peaks:
        if start_h <= hour < end_h:
            mult = max(mult, m)
    return base_per_hour * mult / HOUR


def generate_order_stream(
    demand_cfg: dict,
    scenario: str,
    city: City,
    start_s: float,
    end_s: float,
    rng_orders: np.random.Generator,
    rng_prep: np.random.Generator,
) -> list[OrderSpec]:
    """Generate a day's orders as a non-homogeneous Poisson process.

    Arrivals are generated by *thinning*: candidate times come from a Poisson
    process at the maximum rate, and each is kept with probability
    rate(t) / max_rate. The result is a Poisson process with rate(t).

    Prep times:
      est_prep    = restaurant mean prep * U(1 - spread, 1 + spread)   (shown to dispatchers)
      actual_prep = est_prep * exp(sigma * Z - sigma^2 / 2),  Z ~ N(0, 1)
    The lognormal factor has mean 1, so estimates are unbiased but noisy.
    The Z values come from a separate RNG stream, so runs that differ only in
    sigma see exactly the same orders and the same "luck" (paired comparison).
    """
    base = demand_cfg["base_rate_per_hour"]
    peaks = demand_cfg["scenarios"][scenario]["peaks"]
    max_rate = base * max([1.0] + [p[2] for p in peaks]) / HOUR
    spread = demand_cfg["est_prep_spread"]
    lo_dl, hi_dl = demand_cfg["deadline_window_min"]

    raw = []
    t = start_s
    while max_rate > 0:  # a zero order rate simply produces no orders
        t += rng_orders.exponential(1.0 / max_rate)
        if t >= end_s:
            break
        if rng_orders.random() >= arrival_rate(t, base, peaks) / max_rate:
            continue
        rest = city.restaurants[int(rng_orders.integers(len(city.restaurants)))]
        customer = city.sample_customer_node(rng_orders)
        est = rest.mean_prep_s * rng_orders.uniform(1 - spread, 1 + spread)
        window = rng_orders.uniform(lo_dl, hi_dl) * 60.0
        raw.append((t, rest.node, customer, est, window))

    sigma = demand_cfg["prep_noise_sigma"]
    z = rng_prep.standard_normal(len(raw))
    noise = np.exp(sigma * z - sigma**2 / 2)
    return [
        OrderSpec(i, r_node, c_node, float(t), float(est), float(est * f), float(t + w))
        for i, ((t, r_node, c_node, est, w), f) in enumerate(zip(raw, noise))
    ]
